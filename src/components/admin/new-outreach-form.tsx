import { useRef, useState } from 'react'
import type { ComponentProps, FormEvent, KeyboardEvent } from 'react'
import { useMutation, useQueryClient } from '@tanstack/react-query'
import { z } from 'zod'
import { Button } from '#/components/ui/button'
import { Input } from '#/components/ui/input'
import { Label } from '#/components/ui/label'
import { Textarea } from '#/components/ui/textarea'
import { supabase } from '#/lib/supabase'

type Field = 'name' | 'email' | 'instagram' | 'phone' | 'notes'
type Values = Record<Field, string>
type Errors = Partial<Record<Field | 'form', string>>

const EMPTY: Values = {
  name: '',
  email: '',
  instagram: '',
  phone: '',
  notes: '',
}

const text = z.string().trim()

const schema = z
  .object({
    name: text,
    email: text.pipe(z.union([z.literal(''), z.email('Enter a valid email.')])),
    instagram: text,
    phone: text,
    notes: text,
  })
  .refine((v) => v.name || v.email || v.instagram || v.phone, {
    message: 'Fill in at least one of name, email, Instagram or phone.',
  })

/** Which field each unique index guards, for Postgres duplicate errors. */
const UNIQUE_INDEXES = {
  outreach_email_uq: 'email',
  outreach_instagram_uq: 'instagram',
  outreach_phone_uq: 'phone',
} as const satisfies Record<string, Field>

const DUPLICATE_LABEL = {
  email: 'email',
  instagram: 'Instagram',
  phone: 'phone number',
} as const

/** The field a unique_violation (23505) is about, from the index it names. */
function duplicateField(error: unknown) {
  if (typeof error !== 'object' || error === null) return null
  const { code, message, details } = error as Record<string, unknown>
  if (code !== '23505') return null
  const haystack = `${String(message)} ${String(details)}`
  for (const [index, field] of Object.entries(UNIQUE_INDEXES)) {
    if (haystack.includes(index)) return field
  }
  return null
}

function NewOutreachForm() {
  const queryClient = useQueryClient()
  const [values, setValues] = useState<Values>(EMPTY)
  const [errors, setErrors] = useState<Errors>({})
  const firstField = useRef<HTMLInputElement>(null)

  const add = useMutation({
    mutationFn: async (contact: Values) => {
      // Only these five columns: the *_norm ones are generated by the DB.
      const { error } = await supabase.from('outreach_contacts').insert({
        name: contact.name || null,
        email: contact.email || null,
        instagram: contact.instagram || null,
        phone: contact.phone || null,
        notes: contact.notes || null,
      })
      if (error) throw error
    },
    onSuccess: () => {
      setValues(EMPTY)
      setErrors({})
      firstField.current?.focus()
      return queryClient.invalidateQueries({ queryKey: ['outreach_contacts'] })
    },
    onError: (error) => {
      const field = duplicateField(error)
      setErrors(
        field
          ? {
              [field]: `A contact with this ${DUPLICATE_LABEL[field]} already exists.`,
            }
          : { form: `Couldn't add the contact: ${error.message}` },
      )
    },
  })

  function handleSubmit(event: FormEvent) {
    event.preventDefault()
    if (add.isPending) return

    const result = schema.safeParse(values)
    if (!result.success) {
      const next: Errors = {}
      for (const issue of result.error.issues) {
        const key = (issue.path[0] as Field | undefined) ?? 'form'
        next[key] ??= issue.message
      }
      setErrors(next)
      return
    }

    setErrors({})
    add.mutate(result.data)
  }

  function update(field: Field, value: string) {
    setValues((v) => ({ ...v, [field]: value }))
    if (errors[field] || errors.form) {
      setErrors((e) => ({ ...e, [field]: undefined, form: undefined }))
    }
  }

  // Enter adds the contact from the notes too; Shift+Enter is a new line.
  function handleNotesKeyDown(event: KeyboardEvent<HTMLTextAreaElement>) {
    if (
      event.key === 'Enter' &&
      !event.shiftKey &&
      !event.nativeEvent.isComposing
    ) {
      event.preventDefault()
      event.currentTarget.form?.requestSubmit()
    }
  }

  return (
    <section className="flex flex-col gap-4">
      <h2 className="m-0 text-base font-bold">New outreach</h2>
      <form
        onSubmit={handleSubmit}
        noValidate
        className="flex flex-col gap-3 rounded-lg p-4 shadow-[inset_0_0_0_1px_rgba(255,255,255,.08)] md:p-5"
      >
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          <TextField
            ref={firstField}
            field="name"
            label="Name"
            autoComplete="off"
            values={values}
            errors={errors}
            onChange={update}
          />
          <TextField
            field="email"
            label="Email"
            type="email"
            autoComplete="off"
            values={values}
            errors={errors}
            onChange={update}
          />
          <TextField
            field="instagram"
            label="Instagram"
            placeholder="@handle"
            autoComplete="off"
            values={values}
            errors={errors}
            onChange={update}
          />
          <TextField
            field="phone"
            label="Phone"
            type="tel"
            autoComplete="off"
            values={values}
            errors={errors}
            onChange={update}
          />
        </div>

        <div className="flex flex-col gap-2">
          <Label htmlFor="outreach-notes">Notes</Label>
          <Textarea
            id="outreach-notes"
            rows={2}
            value={values.notes}
            onChange={(e) => update('notes', e.target.value)}
            onKeyDown={handleNotesKeyDown}
            className="min-h-11 rounded-lg border-none bg-white/8 px-4 py-2.5 text-base shadow-none transition-shadow duration-250 placeholder:text-foreground/45 focus-visible:ring-2 focus-visible:ring-foreground/30 md:text-base"
          />
        </div>

        <div className="flex flex-wrap items-center justify-end gap-3">
          {errors.form && (
            <p role="alert" className="m-0 mr-auto text-sm text-[#ff8a7e]">
              {errors.form}
            </p>
          )}
          <Button type="submit" disabled={add.isPending}>
            {add.isPending ? 'Adding…' : 'Add'}
          </Button>
        </div>
      </form>
    </section>
  )
}

interface TextFieldProps extends Omit<
  ComponentProps<'input'>,
  'onChange' | 'value'
> {
  field: Exclude<Field, 'notes'>
  label: string
  values: Values
  errors: Errors
  onChange: (field: Field, value: string) => void
}

function TextField({
  field,
  label,
  values,
  errors,
  onChange,
  ...props
}: TextFieldProps) {
  const id = `outreach-${field}`
  const error = errors[field]

  return (
    <div className="flex flex-col gap-2">
      <Label htmlFor={id}>{label}</Label>
      <Input
        id={id}
        value={values[field]}
        onChange={(e) => onChange(field, e.target.value)}
        aria-invalid={!!error}
        aria-describedby={error ? `${id}-error` : undefined}
        {...props}
      />
      {error && (
        <span
          id={`${id}-error`}
          role="alert"
          className="text-sm text-[#ff8a7e]"
        >
          {error}
        </span>
      )}
    </div>
  )
}

export { NewOutreachForm }
